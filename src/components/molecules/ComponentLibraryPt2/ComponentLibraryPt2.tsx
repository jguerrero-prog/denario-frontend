/* ── Shared card primitives ── */
function Divider() {
  return <div className={styles.divider} />;
}

function SectionHeading({ children }: { children: React.ReactNode }) {
  return <p className={styles.sectionHeading}>{children}</p>;
}

interface TagChipProps { label: string }
function TagChip({ label }: TagChipProps) {
  return (
    <div className={styles.tagChip}>
      <span className={styles.tagChipText}>{label}</span>
    </div>
  );
}

interface ActionRowProps { ghost: string; primary: string }
function ActionRow({ ghost, primary }: ActionRowProps) {
  return (
    <div className={styles.actionRow}>
      <button className={styles.ghostBtn}>{ghost}</button>
      <button className={styles.primaryBtn}>{primary}</button>
    </div>
  );
}

interface TagRowProps { tags: string[] }
function TagRow({ tags }: TagRowProps) {
  return (
    <div className={styles.tagRow}>
      {tags.map((t) => <TagChip key={t} label={t} />)}
    </div>
  );
}

interface CardHeaderProps {
  filename: string;
  source: string;
  timestamp: string;
}
function CardHeader({ filename, source, timestamp }: CardHeaderProps) {
  return (
    <div className={styles.cardHeader}>
      <div className={styles.headerLeft}>
        <span className={styles.statusDot} />
        <div className={styles.fileChip}>
          <span className={styles.fileChipText}>{filename}</span>
        </div>
        <div className={styles.headerSep} />
        <span className={styles.headerSource}>{source}</span>
      </div>
      <span className={styles.headerTime}>{timestamp}</span>
    </div>
  );
}

interface ArtifactCardProps {
  specimenLabel: string;
  footerNote: string;
  children: React.ReactNode;
}
function ArtifactCard({ specimenLabel, footerNote, children }: ArtifactCardProps) {
  return (
    <>
      <p className={styles.specimenLabel}>{specimenLabel}</p>
      <div className={styles.card}>{children}</div>
      <p className={styles.cardFooterNote}>{footerNote}</p>
    </>
  );
}

interface SectionLabelProps { label: string }
function SectionLabel({ label }: SectionLabelProps) {
  return (
    <div className={styles.sectionLabel}>
      <Divider />
      <p className={styles.sectionLabelText}>{label}</p>
    </div>
  );
}

