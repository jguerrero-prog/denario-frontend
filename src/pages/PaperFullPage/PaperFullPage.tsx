// ── PDF view: bar chart SVG ────────────────────────────────────────────────────

function PdfBarChart() {
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug'];
  const blue  = [45, 62, 58, 43, 61, 50, 55, 47];
  const orange = [32, 22, 28, 25, 20, 32, 35, 38];
  const W = 280, H = 120, padL = 28, padB = 18, padT = 8, chartW = W - padL - 8, chartH = H - padB - padT;
  const maxVal = 70;
  const barW = chartW / months.length / 2.5;
  const groupW = chartW / months.length;

  return (
    <svg viewBox={`0 0 ${W} ${H}`} width={W} height={H} className={styles.pdfChart}>
      {/* y-axis labels */}
      {[0, 20, 40, 60].map(v => {
        const y = padT + chartH - (v / maxVal) * chartH;
        return (
          <g key={v}>
            <text x={padL - 4} y={y + 3} textAnchor="end" fontSize="7" fill="#9ca3af">{v}</text>
            <line x1={padL} y1={y} x2={padL + chartW} y2={y} stroke="#e5e7eb" strokeWidth="0.5" />
          </g>
        );
      })}
      {/* bars */}
      {months.map((m, i) => {
        const bx = padL + i * groupW + groupW / 2 - barW - 1;
        const bh = (blue[i] / maxVal) * chartH;
        const oh = (orange[i] / maxVal) * chartH;
        return (
          <g key={m}>
            <rect x={bx} y={padT + chartH - bh} width={barW} height={bh} fill="#3b82f6" rx="1" />
            <rect x={bx + barW + 2} y={padT + chartH - oh} width={barW} height={oh} fill="#f97316" rx="1" />
            <text x={bx + barW + 1} y={H - 4} textAnchor="middle" fontSize="6.5" fill="#9ca3af">{m}</text>
          </g>
        );
      })}
      {/* axes */}
      <line x1={padL} y1={padT} x2={padL} y2={padT + chartH} stroke="#d1d5db" strokeWidth="0.75" />
      <line x1={padL} y1={padT + chartH} x2={padL + chartW} y2={padT + chartH} stroke="#d1d5db" strokeWidth="0.75" />
    </svg>
  );
}

