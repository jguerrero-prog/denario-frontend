// ── Overwrite dialog (245:314) ─────────────────────────────────────────────────

type OverwriteOption = 'save-regen' | 'save-only' | 'discard-regen' | 'cancel-keep';

const OVERWRITE_OPTIONS: Array<{ id: OverwriteOption; label: string; desc: string }> = [
  { id: 'save-regen',      label: 'Save my edits, then regenerate',  desc: 'Downloads manuscript.tex before overwriting.' },
  { id: 'save-only',       label: 'Save only — don\'t regenerate',   desc: 'Keeps your edits saved without triggering regeneration.' },
  { id: 'discard-regen',   label: 'Discard my edits and regenerate', desc: 'Your manual changes will be permanently lost.' },
  { id: 'cancel-keep',     label: 'Cancel — keep editing',           desc: 'Stay in the editor without regenerating.' },
];

interface OverwriteDialogProps {
  selected: OverwriteOption;
  onSelect: (o: OverwriteOption) => void;
  onCancel: () => void;
  onContinue: () => void;
}

function OverwriteDialog({ selected, onSelect, onCancel, onContinue }: OverwriteDialogProps) {
  useEffect(() => {
    function handleKey(e: KeyboardEvent) {
      if (e.key === 'Escape') onCancel();
    }
    document.addEventListener('keydown', handleKey);
    return () => document.removeEventListener('keydown', handleKey);
  }, [onCancel]);

  return (
    <div className={styles.dialogOverlay} onClick={e => { if (e.target === e.currentTarget) onCancel(); }}>
      <div className={styles.dialog} role="dialog" aria-modal="true">
        {/* Header */}
        <div className={styles.dialogHeader}>
          <div className={styles.dialogHeaderLeft}>
            <WarnIcon />
            <h2 className={styles.dialogTitle}>Overwrite manual edits?</h2>
          </div>
          <button className={styles.dialogClose} onClick={onCancel} aria-label="Close">
            <svg width="14" height="14" viewBox="0 0 14 14" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round">
              <path d="M2 2l10 10M12 2L2 12" />
            </svg>
          </button>
        </div>

        <p className={styles.dialogBody}>
          You have unsaved manual edits to manuscript.tex. Regenerating Stage 5 will overwrite these changes — they cannot be recovered.
        </p>

        {/* Modified file row */}
        <div className={styles.dialogFileRow}>
          <div className={styles.dialogFileDot} />
          <span className={styles.dialogFileName}>manuscript.tex</span>
          <span className={styles.dialogFileModified}>Modified · 1 change</span>
        </div>

        {/* Options */}
        <p className={styles.dialogOptionsLabel}>WHAT WOULD YOU LIKE TO DO?</p>
        <div className={styles.dialogOptions}>
          {OVERWRITE_OPTIONS.map(opt => (
            <label key={opt.id} className={`${styles.dialogOption} ${selected === opt.id ? styles.dialogOptionSelected : ''}`}>
              <input
                type="radio"
                name="overwrite-action"
                value={opt.id}
                checked={selected === opt.id}
                onChange={() => onSelect(opt.id)}
                className={styles.dialogRadio}
              />
              <div className={styles.dialogOptionText}>
                <span className={styles.dialogOptionLabel}>{opt.label}</span>
                <span className={styles.dialogOptionDesc}>{opt.desc}</span>
              </div>
            </label>
          ))}
        </div>

        {/* Footer */}
        <div className={styles.dialogFooter}>
          <button className={styles.dialogCancelBtn} onClick={onCancel}>Cancel</button>
          <button className={styles.dialogContinueBtn} onClick={onContinue}>Continue →</button>
        </div>
      </div>
    </div>
  );
}

// ── Main component ─────────────────────────────────────────────────────────────

export function PaperFullPage() {
  const navigate = useNavigate();
  const { projectId, stageId = 'paper' } = useParams<{ projectId: string; stageId: string }>();
  const [searchParams] = useSearchParams();
  const view = searchParams.get('view') ?? 'pdf';

  const pipeline = usePipelineStore(s => s.pipeline);
  const stageResult = pipeline?.stages['paper']?.result;
  const data = stageResult?.stageData as PaperResultData | undefined;

  const stageIndex = STAGE_ORDER.indexOf('paper');
  const stageNum = stageIndex >= 0 ? stageIndex + 1 : 5;

  // PDF state
  const [currentPage, setCurrentPage] = useState(1);
  const totalPages = data?.pdfFile?.pages ?? 8;

  // TeX state
  const [texContent, setTexContent]       = useState(TEX_INITIAL);
  const [isDirty, setIsDirty]             = useState(false);
  const [showOverwrite, setShowOverwrite] = useState(false);
  const [selectedOption, setSelectedOption] = useState<OverwriteOption>('save-regen');

  function handleBack() {
    navigate(`/project/${projectId}/stage/${stageId}`);
  }

  function handleTexChange(val: string) {
    setTexContent(val);
    setIsDirty(val !== TEX_INITIAL);
  }

  function handleSave() {
    setIsDirty(false);
  }

  function handleRegen() {
    if (isDirty) {
      setShowOverwrite(true);
    } else {
      handleBack();
    }
  }

  function handleDialogContinue() {
    if (selectedOption === 'save-regen' || selectedOption === 'save-only') {
      handleSave();
    }
    setShowOverwrite(false);
    if (selectedOption === 'save-regen' || selectedOption === 'discard-regen') {
      handleBack();
    }
  }

  if (view === 'tex') {
    return (
      <div className={styles.layout}>
        <Sidebar userEmail="researcher@lab.edu" />
        <main className={styles.main}>
          <TexTopBar
            stageNum={stageNum}
            isDirty={isDirty}
            onBack={handleBack}
            onCopyAll={() => navigator.clipboard?.writeText(texContent)}
            onDownload={() => {}}
            onSave={handleSave}
            onRegen={handleRegen}
          />
          <TexFileTab texFile={data?.texFile} />
          <TexEditor content={texContent} onChange={handleTexChange} />
          {isDirty && (
            <div className={styles.dirtyBar}>
              <span className={styles.dirtyDot} />
              <span className={styles.dirtyText}>Unsaved edits</span>
              <button className={styles.dirtyRegenBtn} onClick={handleRegen}>Regenerate stage</button>
            </div>
          )}
        </main>
        {showOverwrite && createPortal(
          <OverwriteDialog
            selected={selectedOption}
            onSelect={setSelectedOption}
            onCancel={() => setShowOverwrite(false)}
            onContinue={handleDialogContinue}
          />,
          document.body,
        )}
      </div>
    );
  }

  // PDF view
  return (
    <div className={styles.layout}>
      <Sidebar userEmail="researcher@lab.edu" />
      <main className={styles.main}>
        <PdfTopBar
          stageNum={stageNum}
          fileName={data?.pdfFile?.name ?? 'paper.pdf'}
          currentPage={currentPage}
          totalPages={totalPages}
          onBack={handleBack}
          onPrev={() => setCurrentPage(p => Math.max(1, p - 1))}
          onNext={() => setCurrentPage(p => Math.min(totalPages, p + 1))}
        />
        <div className={styles.pdfScrollArea}>
          <PdfPage data={data} pageTitle={stageResult?.title ?? 'Temporal Correlation Between Atmospheric CO₂ Concentration and Surface Temperature Anomalies: A 5-Year Constrained Observational Study (2019–2024)'} />
        </div>
      </main>
    </div>
  );
}
