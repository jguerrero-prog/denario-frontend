// ROADMAP.md ticket 4.4 — minimal RFC-4180-ish CSV parser for the browsable
// data-table viewer. Real generated CSVs seen so far are simple numeric
// tables with no embedded commas, but handling quoted fields (with escaped
// "" and embedded commas/newlines) costs little and avoids silently
// mis-splitting a row if a future script's CSV does use them.

export interface ParsedCsv {
  columns: string[];
  rows: string[][];
}

export function parseCsv(text: string): ParsedCsv {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const next = text[i + 1];

    if (inQuotes) {
      if (char === '"' && next === '"') {
        field += '"';
        i++;
      } else if (char === '"') {
        inQuotes = false;
      } else {
        field += char;
      }
      continue;
    }

    if (char === '"') {
      inQuotes = true;
    } else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n' || char === '\r') {
      if (char === '\r' && next === '\n') i++;
      row.push(field);
      field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else {
      field += char;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  if (rows.length === 0) return { columns: [], rows: [] };
  const [columns, ...body] = rows;
  return { columns, rows: body };
}
